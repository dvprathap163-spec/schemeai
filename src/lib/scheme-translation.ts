export function translateText(text: string, language: SchemeLanguage): string {
  if (!text) return ''
  const map = WORD_MAP[language]
  return text
    .split(/(\s+|[(),.-]+)/)
    .map((part) => {
      const normalized = part.trim().toLowerCase()
      if (!normalized) return part
      const translated = map[normalized]
      return translated ?? part
    })
    .join('')
}

export function buildLocalizedScheme(input: {
  name?: string
  description?: string
  benefits?: string[]
  documents?: string[]
}) {
  return {
    nameHi: input.name ? translateText(input.name, 'hi') : undefined,
    nameTe: input.name ? translateText(input.name, 'te') : undefined,
    nameKn: input.name ? translateText(input.name, 'kn') : undefined,
    nameMl: input.name ? translateText(input.name, 'ml') : undefined,
    nameTa: input.name ? translateText(input.name, 'ta') : undefined,
    descriptionHi: input.description ? translateText(input.description, 'hi') : undefined,
    descriptionTe: input.description ? translateText(input.description, 'te') : undefined,
    descriptionKn: input.description ? translateText(input.description, 'kn') : undefined,
    descriptionMl: input.description ? translateText(input.description, 'ml') : undefined,
    descriptionTa: input.description ? translateText(input.description, 'ta') : undefined,
    benefitsHi: input.benefits?.map((item) => translateText(item, 'hi')),
    benefitsTe: input.benefits?.map((item) => translateText(item, 'te')),
    benefitsKn: input.benefits?.map((item) => translateText(item, 'kn')),
    benefitsMl: input.benefits?.map((item) => translateText(item, 'ml')),
    benefitsTa: input.benefits?.map((item) => translateText(item, 'ta')),
    documentsHi: input.documents?.map((item) => translateText(item, 'hi')),
    documentsTe: input.documents?.map((item) => translateText(item, 'te')),
    documentsKn: input.documents?.map((item) => translateText(item, 'kn')),
    documentsMl: input.documents?.map((item) => translateText(item, 'ml')),
    documentsTa: input.documents?.map((item) => translateText(item, 'ta')),
  }
}

export function getLocalizedSchemeValue<T extends Record<string, any>>(
  scheme: T,
  field: 'name' | 'description' | 'category' | 'ministry' | 'benefits' | 'documents',
  language: string,
) {
  const langMap: Record<string, 'hi' | 'te' | 'kn' | 'ml' | 'ta'> = {
    hi: 'hi',
    te: 'te',
    kn: 'kn',
    ml: 'ml',
    ta: 'ta',
  }
  const lang = langMap[language] || 'en'
  if (language === 'en') return scheme[field] ?? ''
  
  const langSuffix = {
    hi: 'Hi',
    te: 'Te',
    kn: 'Kn',
    ml: 'Ml',
    ta: 'Ta',
  }[lang]
  
  const translatedField = `${field}${langSuffix}` as keyof T
  const value = scheme[translatedField]
  if (Array.isArray(value)) return value
  return value ?? scheme[field] ?? ''
}
